"use client";

import React, { useState } from "react";
import Link from "next/link";
import { ArrowLeft, Check, Copy } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Reveal } from "@/components/ui/reveal";
import { RedesignResponse } from "@/lib/api";

interface ResultHeaderProps {
  result: RedesignResponse;
  onCopySuccess?: () => void;
}

export function ResultHeader({ result, onCopySuccess }: ResultHeaderProps) {
  const [copied, setCopied] = useState(false);

  const handleCopyGuide = async () => {
    const textContent = `
REWEAR AI — UPCYCLING BLUEPRINT
Garment: ${result.garment_type}

[DETECTED DAMAGE]
${result.detected_damage}

[MATERIALS & TOOLS]
${result.materials_needed.map((m, i) => `${i + 1}. ${m}`).join("\n")}

[STEP-BY-STEP UPCYCLING GUIDE]
${result.upcycling_steps.map((s, i) => `Step ${i + 1}: ${s}`).join("\n\n")}

[DESIGN NOTE]
${result.redesign_prompt}

Circular Fashion Blueprint generated by ReWear AI
`.trim();

    try {
      await navigator.clipboard.writeText(textContent);
    } catch {
      const textArea = document.createElement("textarea");
      textArea.value = textContent;
      document.body.appendChild(textArea);
      textArea.select();
      document.execCommand("copy");
      document.body.removeChild(textArea);
    }

    setCopied(true);
    onCopySuccess?.();
    setTimeout(() => setCopied(false), 2400);
  };

  return (
    <header className="w-full flex flex-col md:flex-row md:items-end justify-between gap-6 pb-8 border-b border-[var(--color-hairline,rgba(14,14,14,0.12))]">
      <div className="space-y-3">
        <Reveal delay={0.05}>
          <p className="text-xs font-mono uppercase tracking-[0.25em] text-[var(--color-gray,#6B6860)]">
            Step 03 &mdash; Upcycling Blueprint
          </p>
        </Reveal>

        <Reveal delay={0.15} yOffset={24}>
          <h1 className="font-editorial text-[clamp(2.25rem,5.5vw,4rem)] leading-[1.02] tracking-tight text-[var(--color-ink,#0E0E0E)]">
            Your garment, reborn.
          </h1>
        </Reveal>

        <Reveal delay={0.25}>
          <p className="text-xs font-mono uppercase tracking-widest text-[var(--color-gray,#6B6860)]">
            Garment profile &bull; {result.garment_type}
          </p>
        </Reveal>
      </div>

      <Reveal delay={0.3} className="no-print">
        <div className="flex items-center gap-3">
          <button
            type="button"
            onClick={handleCopyGuide}
            className="min-h-[44px] px-4 py-2 text-xs font-mono uppercase tracking-wider text-[var(--color-ink,#0E0E0E)] border border-[var(--color-hairline,rgba(14,14,14,0.18))] rounded-full hover:bg-black/[0.04] transition-colors flex items-center gap-2 cursor-pointer focus-visible:outline-2"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 stroke-[2.5]" />
                <span>Copied</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy guide</span>
              </>
            )}
          </button>

          <Link href="/upload">
            <Button
              size="sm"
              className="min-h-[44px] px-5 text-xs font-mono uppercase tracking-wider"
            >
              <ArrowLeft className="w-3.5 h-3.5 mr-2" />
              <span>Try another garment</span>
            </Button>
          </Link>
        </div>
      </Reveal>
    </header>
  );
}
